#!/bin/bash

# Manual Install Snapshot Script
# Records what is installed outside Nix and Homebrew (global npm/cargo/pip
# packages, uv/pipx tools, ~/.local/bin, App Store and drag-installed apps)
# so it can be reinstalled by hand after a restore.
#
# Usage:
#   ./snapshot-manual-installs.sh           Write manual-installs.txt
#   ./snapshot-manual-installs.sh --print   Print the current list only

FLAKE_DIR="$(cd "$(dirname "$0")" && pwd)"
SNAPSHOT="$FLAKE_DIR/manual-installs.txt"
BREW="/opt/homebrew/bin/brew"

export PATH="$HOME/.npm-global/bin:$HOME/.cargo/bin:$HOME/.local/bin:/opt/homebrew/bin:$PATH"

# Apps installed by Homebrew casks: names from cask metadata, plus cask tokens
# as a fallback for casks whose metadata brew cannot read
cask_apps() {
  [ -x "$BREW" ] || return
  "$BREW" info --cask --installed --json=v2 2>/dev/null |
    jq -r '.casks[].artifacts[] | objects | .app? // empty | .[] | strings' 2>/dev/null
  "$BREW" list --cask -1 2>/dev/null
}

# Normalise "Visual Studio Code.app" and "visual-studio-code" to one form
normalise() {
  sed -e 's/\.app$//' -e 's/[ _]/-/g' | tr '[:upper:]' '[:lower:]'
}

collect() {
  # Global npm packages
  if command -v npm >/dev/null; then
    npm ls -g --depth=0 --json 2>/dev/null |
      jq -r '.dependencies // {} | keys[]' | grep -vx 'npm\|corepack' | sed 's/^/npm: /'
  fi

  # Cargo-installed crates
  if command -v cargo >/dev/null; then
    cargo install --list 2>/dev/null | grep -E '^[^ ]' | cut -d' ' -f1 | sed 's/^/cargo: /'
  fi

  # Python tools and user-site packages
  if command -v uv >/dev/null; then
    uv tool list 2>/dev/null | grep -E '^[^ -]' | grep -v '^No tools' | cut -d' ' -f1 | sed 's/^/uv-tool: /'
  fi
  if command -v pipx >/dev/null; then
    pipx list --short 2>/dev/null | cut -d' ' -f1 | sed 's/^/pipx: /'
  fi
  /usr/bin/python3 -m pip list --user --format=freeze 2>/dev/null | cut -d= -f1 | sed 's/^/pip-user: /'

  # Hand-placed binaries
  if [ -d "$HOME/.local/bin" ]; then
    ls -1 "$HOME/.local/bin" | sed 's/^/local-bin: /'
  fi

  # App Store apps not in homebrew.masApps (id kept so `mas install <id>`
  # can restore them)
  if command -v mas >/dev/null; then
    local mas_ids
    mas_ids="$(nix eval --raw "$FLAKE_DIR#darwinConfigurations.m4max.config.homebrew.masApps" \
      --apply 'a: builtins.concatStringsSep "\n" (map toString (builtins.attrValues a))' 2>/dev/null)"
    mas list 2>/dev/null |
      sed -E 's/^ *([0-9]+) +(.*[^ ]) +\(.*\)$/\1 \2/' |
      while read -r id name; do
        printf '%s\n' "$mas_ids" | grep -qx "$id" && continue
        echo "mas: $name ($id)"
      done
  fi

  # Apps not from Homebrew, Nix or the App Store (drag-installed / own installer)
  local managed
  managed="$(cask_apps | normalise | sort -u)"
  for app in /Applications/*.app "$HOME"/Applications/*.app; do
    [ -d "$app" ] || continue
    [ -L "$app" ] && continue                       # system/Nix symlinks (Safari, Nix Apps)
    [ -d "$app/Contents/_MASReceipt" ] && continue  # App Store, listed above
    name="$(basename "$app" .app)"
    printf '%s\n' "$managed" | grep -qx "$(printf '%s' "$name" | normalise)" && continue
    echo "app: $name"
  done
}

if [ "$1" = "--print" ]; then
  collect | LC_ALL=C sort -u
  exit 0
fi

{
  echo "# Software installed outside Nix/Homebrew. Generated by snapshot-manual-installs.sh;"
  echo "# reinstall these by hand after a restore. Update with ./snapshot-manual-installs.sh"
  collect | LC_ALL=C sort -u
} > "$SNAPSHOT"

echo "📸 Wrote $(grep -vc '^#' "$SNAPSHOT") entries to $SNAPSHOT"
